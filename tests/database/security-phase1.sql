-- Run against a disposable PostgreSQL database only, after the fixture setup
-- in run-security-phase1.sh. Production functions are loaded from NEW migrations.
DO $$
DECLARE owner_id uuid := '10000000-0000-0000-0000-000000000001';
  member_id uuid := '10000000-0000-0000-0000-000000000002';
  source_id uuid := '20000000-0000-0000-0000-000000000001';
  dest_id uuid := '20000000-0000-0000-0000-000000000002';
  task_id uuid := '30000000-0000-0000-0000-000000000001';
  i int; claimed uuid; claim_id uuid;
BEGIN
  PERFORM set_config('request.jwt.claim.role','service_role',true);
  PERFORM set_config('request.headers',json_build_object('x-foco-actor-id',member_id)::text,true);
  ASSERT public.current_actor_id()=member_id, 'service actor header';
  PERFORM set_config('request.jwt.claim.role','authenticated',true);
  ASSERT public.current_actor_id() IS NULL, 'untrusted actor header rejected';
  PERFORM set_config('request.jwt.claim.sub',member_id::text,true);
  ASSERT public.current_actor_id()=member_id, 'authenticated subject wins';
  INSERT INTO projects(id,user_id) VALUES(source_id,owner_id),(dest_id,member_id);
  INSERT INTO project_members(project_id,user_id,role) VALUES(source_id,member_id,'member');
  INSERT INTO tasks(id,user_id,project_id,assignee_id) VALUES(task_id,owner_id,source_id,member_id);
  BEGIN UPDATE tasks SET user_id=member_id WHERE id=task_id; RAISE EXCEPTION 'TEST_FAILED takeover allowed';
    EXCEPTION WHEN raise_exception THEN IF SQLERRM LIKE 'TEST_FAILED%' THEN RAISE; END IF; END;
  BEGIN UPDATE tasks SET project_id=dest_id WHERE id=task_id; RAISE EXCEPTION 'TEST_FAILED source bypass allowed';
    EXCEPTION WHEN raise_exception THEN IF SQLERRM LIKE 'TEST_FAILED%' THEN RAISE; END IF; END;
  PERFORM set_config('request.jwt.claim.sub',owner_id::text,true);
  UPDATE tasks SET title='owner can edit',assignee_id=NULL WHERE id=task_id;
  ASSERT (SELECT title='owner can edit' AND assignee_id IS NULL FROM tasks WHERE id=task_id), 'owner edits';
  BEGIN UPDATE tasks SET project_id=dest_id WHERE id=task_id; RAISE EXCEPTION 'TEST_FAILED destination access ignored';
    EXCEPTION WHEN raise_exception THEN IF SQLERRM LIKE 'TEST_FAILED%' THEN RAISE; END IF; END;
  INSERT INTO project_members(project_id,user_id,role) VALUES(dest_id,owner_id,'member');
  UPDATE tasks SET project_id=dest_id,user_id=member_id WHERE id=task_id;
  ASSERT (SELECT user_id=member_id AND project_id=dest_id FROM tasks WHERE id=task_id), 'owner transfer with destination access';
  PERFORM set_config('request.jwt.claim.sub','',true);
  PERFORM set_config('request.jwt.claim.role','service_role',true);
  PERFORM set_config('request.headers','{"x-foco-actor-id":"bad-uuid"}',true);
  ASSERT public.current_actor_id() IS NULL, 'malformed actor safe';
  INSERT INTO auth.users(id,email,email_confirmed_at) VALUES(owner_id,'owner@anpla.com.br',now()),(member_id,'member@anpla.com.br',now());
  INSERT INTO profiles(user_id,email) VALUES(owner_id,'owner@anpla.com.br'),(member_id,'member@anpla.com.br');
  PERFORM set_config('request.jwt.claim.role','authenticated',true);
  UPDATE profiles SET email='attacker@example.com' WHERE user_id=owner_id;
  ASSERT (SELECT email='owner@anpla.com.br' FROM profiles WHERE user_id=owner_id), 'profile email immutable';
  UPDATE auth.users SET email='new@anpla.com.br' WHERE id=owner_id;
  ASSERT (SELECT email='new@anpla.com.br' FROM profiles WHERE user_id=owner_id), 'auth email sync';
  FOR i IN 1..20 LOOP
    IF i%3=0 THEN INSERT INTO project_invites(project_id,email,token,invited_by) VALUES(source_id,'invite'||i||'@example.com',i::text,owner_id);
    ELSIF i%3=1 THEN INSERT INTO contact_invites(email,token,inviter_id) VALUES('invite'||i||'@example.com',i::text,owner_id);
    ELSE INSERT INTO team_invites(team_id,email,token,invited_by) VALUES(source_id,'invite'||i||'@example.com',i::text,owner_id); END IF;
  END LOOP;
  ASSERT (SELECT count(*)=20 FROM invitation_send_log WHERE user_id=owner_id), '20 combined invites allowed';
  BEGIN INSERT INTO contact_invites(email,token,inviter_id) VALUES('21@example.com','21',owner_id); RAISE EXCEPTION 'TEST_FAILED 21st invite allowed';
    EXCEPTION WHEN raise_exception THEN IF SQLERRM NOT LIKE '%20 convites em 24 horas%' THEN RAISE; END IF; END;
  BEGIN INSERT INTO auth.users(id,email) VALUES(gen_random_uuid(),'outsider@example.com'); RAISE EXCEPTION 'TEST_FAILED outsider signup allowed';
    EXCEPTION WHEN raise_exception THEN IF SQLERRM NOT LIKE 'FOCO_SIGNUP_RESTRICTED%' THEN RAISE; END IF; END;
  INSERT INTO auth.users(id,email) VALUES(gen_random_uuid(),'invite1@example.com');
  UPDATE contact_invites SET expires_at=now()-interval '1 second' WHERE email='invite1@example.com';
  BEGIN INSERT INTO auth.users(id,email) VALUES(gen_random_uuid(),'invite1@example.com'); RAISE EXCEPTION 'TEST_FAILED expired invitation signup allowed';
    EXCEPTION WHEN raise_exception THEN IF SQLERRM NOT LIKE 'FOCO_SIGNUP_RESTRICTED%' THEN RAISE; END IF; END;
  PERFORM set_config('request.jwt.claim.sub',member_id::text,true);
  UPDATE profiles SET email='invite4@example.com' WHERE user_id=member_id;
  BEGIN PERFORM accept_contact_invite('4'); RAISE EXCEPTION 'TEST_FAILED spoofed profile invitation accepted';
    EXCEPTION WHEN raise_exception THEN IF SQLERRM NOT LIKE '%outro e-mail%' THEN RAISE; END IF; END;
  UPDATE auth.users SET email_confirmed_at=NULL WHERE id=member_id;
  BEGIN PERFORM accept_contact_invite('4'); RAISE EXCEPTION 'TEST_FAILED unconfirmed email accepted';
    EXCEPTION WHEN raise_exception THEN IF SQLERRM NOT LIKE 'Confirme seu e-mail%' THEN RAISE; END IF; END;
  INSERT INTO notifications(id,user_id,type,title) SELECT gen_random_uuid(),owner_id,'task_assigned','test' FROM generate_series(1,60);
  ASSERT (SELECT count(*)=50 FROM claim_pending_notifications()), 'claim limit 50';
  ASSERT (SELECT count(*)=10 FROM claim_pending_notifications()), 'claimed rows excluded';
  ASSERT (SELECT count(*)=0 FROM claim_pending_notifications()), 'no double reservation';
  SELECT id,delivery_claim_id INTO claimed,claim_id FROM notifications LIMIT 1;
  PERFORM finish_notification_delivery(claimed,claim_id,true,true,false,'test failure');
  ASSERT (SELECT emailed_at IS NULL AND teams_sent_at IS NOT NULL AND delivery_claim_id IS NULL FROM notifications WHERE id=claimed), 'retry preserves Teams success';
  ASSERT (SELECT count(*)=1 FROM claim_pending_notifications()), 'failed send retry';
  ASSERT NOT has_column_privilege('authenticated','contact_invites','token','SELECT'), 'invite token unreadable';
  ASSERT NOT has_function_privilege('authenticated','claim_pending_notifications()','EXECUTE'), 'claim service-only';
  ASSERT NOT has_table_privilege('authenticated','cron_credentials','SELECT'), 'cron secret unreadable';
  RAISE NOTICE 'PASS ownership, source/destination access, actor trust, email sync, combined 20/24h limit, signup eligibility, confirmed invitation identity, notification reservations and grants';
END $$;